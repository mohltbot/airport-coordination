"""Generate bundled geographic paths from us-atlas 3.0.1 and OurAirports CSV.
Usage: python3 web/scripts/build-us-geography.py /path/states-10m.json /path/airports.csv
Source URLs, license and ranking are recorded in web/MAP-SOURCES.md.
No map server or API key is needed at runtime.
"""
import csv, json, pathlib, sys
root = pathlib.Path(__file__).resolve().parents[1]
topology = json.load(open(sys.argv[1]))
transform = topology['transform']
def project(lon, lat):
    return [round(12 + (lon + 125) * 3.65, 4), round(17 + (50 - lat) * 4.65, 4)]
arcs = []
for arc in topology['arcs']:
    x = y = 0
    points = []
    for dx, dy in arc:
        x += dx; y += dy
        lon = x * transform['scale'][0] + transform['translate'][0]
        lat = y * transform['scale'][1] + transform['translate'][1]
        points.append(project(lon, lat))
    arcs.append(points)
def ring_path(ring):
    points = []
    for i in ring:
        segment = arcs[i] if i >= 0 else list(reversed(arcs[~i]))
        points.extend(segment if not points else segment[1:])
    return 'M' + 'L'.join(f'{x:g},{y:g}' for x,y in points) + 'Z'
states = []
for geo in topology['objects']['states']['geometries']:
    if geo['id'] in ['02','15'] or int(geo['id']) > 56: continue
    polygons = [geo['arcs']] if geo['type'] == 'Polygon' else geo['arcs']
    states.append({'name':geo['properties']['name'], 'path':''.join(ring_path(ring) for polygon in polygons for ring in polygon)})
ids = ['ATL','DFW','DEN','ORD','LAX','JFK','CLT','LAS','MCO','MIA','SFO','OAK','SJC','MRY','EWR','LGA']
rows = {r['iata_code']:r for r in csv.DictReader(open(sys.argv[2])) if r['iata_code'] in ids and r['iso_country']=='US'}
airports = []
for rank,code in enumerate(ids,1):
    r=rows[code]; lon=float(r['longitude_deg']); lat=float(r['latitude_deg']); x,y=project(lon,lat)
    name = r['name'].replace('Hartsfield Jackson','Hartsfield–Jackson')
    airports.append({'airportId':code,'name':name,'city':r['municipality'],'latitude':lat,'longitude':lon,'rank':rank if rank <= 10 else None,'position':{'x':x,'y':y}})
text = '''// Generated by web/scripts/build-us-geography.py. Census/us-atlas (ISC), OurAirports (public domain).
// The geography is real; distances are deliberately compressed for the simulator.
export const projectUs = (longitude: number, latitude: number) => ({
  x: 12 + (longitude + 125) * 3.65,
  y: 17 + (50 - latitude) * 4.65,
});
'''
text += 'export const US_AIRPORTS = '+json.dumps(airports,ensure_ascii=False,indent=2)+' as const;\n'
text += 'export const US_STATES: {name: string; path: string}[] = '+json.dumps(states,ensure_ascii=False,separators=(',',':'))+';\n'
(root/'src/lib/us-geography.ts').write_text(text)
print(f'Generated {len(states)} states and {len(airports)} airports, {len(text)} bytes')
